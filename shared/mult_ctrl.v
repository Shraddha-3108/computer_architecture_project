module mult_ctrl(
    input  [7:0] state,
    input  [31:0] IR,

    // control outputs
    output reg IRLd,
    output reg RegWr,
    output reg RegEn,
    output reg [2:0] RegSel,

    output reg ALd,
    output reg BLd,
    output reg MALd,

    output reg [2:0] ALUOp,
    output reg ALUEn,

    output reg MemWr,
    output reg MemEn,

    output reg [2:0] ImmSel,
    output reg ImmEn,

    // to sequencer
    output [2:0] uBr,
    output [7:0] next
);

    reg [31:0] ROM [0:255];
    wire [31:0] uinstr = ROM[state];

    // =========================
    // Decode
    // =========================
    always @(*) begin
        IRLd   = uinstr[20];
        RegWr  = uinstr[19];
        RegEn  = uinstr[18];
        RegSel = uinstr[17:15];

        ALd    = uinstr[14];
        BLd    = uinstr[13];
        MALd   = uinstr[12];

        ALUOp  = uinstr[11:9];   // FIXED (3-bit)
        ALUEn  = uinstr[8];

        MemWr  = uinstr[7];
        MemEn  = uinstr[6];

        ImmSel = uinstr[5:3];
        ImmEn  = uinstr[2];
    end

    assign uBr  = uinstr[23:21];
    assign next = uinstr[31:24];

    // =========================
    // ROM
    // =========================
    initial begin

    // ===== FETCH =====
    ROM[0] = {8'd1,3'b000,0,0,1,3'b000,1,0,1,3'b110,0,0,0,3'b000,0}; // MA←PC, A←PC
    ROM[1] = {8'd2,3'b101,1,0,0,3'b000,0,0,0,3'b000,0,0,1,3'b000,0}; // IR←Mem
    ROM[2] = {8'd0,3'b100,0,1,0,3'b000,0,0,0,3'b101,1,0,0,3'b000,0}; // PC+4

    // ===== ADD =====
    ROM[10] = {8'd11,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0}; // A←rs1
    ROM[11] = {8'd12,3'b000,0,0,1,3'b100,0,1,0,3'b000,0,0,0,3'b000,0}; // B←rs2
    ROM[12] = {8'd0,3'b001,0,1,0,3'b010,0,0,0,3'b000,1,0,0,3'b000,0}; // rd←A+B

    // ===== SUB =====
    ROM[20] = {8'd21,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0};
    ROM[21] = {8'd22,3'b000,0,0,1,3'b100,0,1,0,3'b000,0,0,0,3'b000,0};
    ROM[22] = {8'd0,3'b001,0,1,0,3'b010,0,0,0,3'b001,1,0,0,3'b000,0};

    // ===== ADDI =====
    ROM[30] = {8'd31,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0};
    ROM[31] = {8'd32,3'b000,0,0,0,3'b000,0,1,0,3'b000,0,0,0,3'b000,1}; // ImmI
    ROM[32] = {8'd0,3'b001,0,1,0,3'b010,0,0,0,3'b000,1,0,0,3'b000,0};

    // ===== XORI =====
    ROM[40] = {8'd41,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0};
    ROM[41] = {8'd42,3'b000,0,0,0,3'b000,0,1,0,3'b000,0,0,0,3'b000,1};
    ROM[42] = {8'd0,3'b001,0,1,0,3'b010,0,0,0,3'b100,1,0,0,3'b000,0};

    // ===== LW =====
    ROM[50] = {8'd51,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0};
    ROM[51] = {8'd52,3'b000,0,0,0,3'b000,0,1,0,3'b000,0,0,0,3'b000,1};
    ROM[52] = {8'd53,3'b000,0,0,0,3'b000,0,0,1,3'b000,1,0,0,3'b000,0};
    ROM[53] = {8'd54,3'b101,0,0,0,3'b000,0,0,0,3'b000,0,0,1,3'b000,0};
    ROM[54] = {8'd0,3'b001,0,1,0,3'b010,0,0,0,3'b110,0,0,1,3'b000,0};

    // ===== SW =====
    ROM[60] = {8'd61,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0};
    ROM[61] = {8'd62,3'b000,0,0,0,3'b000,0,1,0,3'b000,0,0,0,3'b001,1};
    ROM[62] = {8'd63,3'b000,0,0,0,3'b000,0,0,1,3'b000,1,0,0,3'b000,0};
    ROM[63] = {8'd63,3'b101,0,0,1,3'b100,0,0,0,3'b000,0,1,0,3'b000,0};
    ROM[64] = {8'd0,3'b001,0,0,0,3'b000,0,0,0,3'b000,0,0,0,3'b000,0};

    // ===== BNE (FIXED) =====
    ROM[70] = {8'd71,3'b000,0,0,1,3'b011,1,0,0,3'b000,0,0,0,3'b000,0}; // A←rs1
    ROM[71] = {8'd72,3'b000,0,0,1,3'b100,0,1,0,3'b000,0,0,0,3'b000,0}; // B←rs2
    ROM[72] = {8'd73,3'b000,0,0,0,3'b000,0,1,0,3'b001,1,0,0,3'b000,0}; // B←A-B
    ROM[73] = {8'd74,3'b011,0,0,0,3'b000,0,0,0,3'b000,0,0,0,3'b000,0}; // NZ
    ROM[74] = {8'd75,3'b000,0,1,0,3'b000,0,0,0,3'b000,1,0,0,3'b010,1}; // PC+ImmB
    ROM[75] = {8'd0,3'b001,0,0,0,3'b000,0,0,0,3'b000,0,0,0,3'b000,0};

    end

endmodule